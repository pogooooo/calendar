// Asset preparation only. Generated neutral sources remain the single source of material detail.
import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { materialRamp, DEFAULT_MATERIAL_COLOR } from "../src/features/gem/materials/materialPalette.ts";
import { materialCrops } from "../src/features/gem/materials/materialCrops.ts";

const root = new URL("../src/features/gem/materials/", import.meta.url);
await mkdir(new URL("generated/", root), { recursive: true });
for (const role of ["cut", "quartz", "pearl", "geode", "gold", "silver"]) {
    const source = role === "gold" || role === "silver" ? "metal" : role;
    const { data, info } = await sharp(fileURLToPath(new URL(`${source}-neutral.webp`, root))).greyscale().raw().toBuffer({ resolveWithObject: true });
    const modes = role === "gold" || role === "silver" || role === "cut" ? ["light"] : ["light", "dark"];
    for (const mode of modes) {
        const ramp = materialRamp(DEFAULT_MATERIAL_COLOR, mode, role);
        const lut = Array.from({ length: 256 }, (_, v) => {
            const position = v / 255 * (ramp.length - 1);
            const a = Math.min(ramp.length - 2, Math.floor(position));
            const t = position - a;
            return ramp[a].map((c, i) => Math.round(c + (ramp[a + 1][i] - c) * t));
        });
        const rgb = Buffer.alloc(info.width * info.height * 3);
        for (let i = 0; i < data.length; i++) rgb.set(lut[data[i]], i * 3);
        const name = `${role}${modes.length > 1 ? `-${mode}` : ""}.webp`;
        await sharp(rgb, { raw: { width: info.width, height: info.height, channels: 3 } }).webp({ quality: 95, effort: 5 }).toFile(fileURLToPath(new URL(`generated/${name}`, root)));
        console.log(name);
    }
    if (!["gold", "silver", "geode"].includes(role)) {
        const mask = Buffer.from(data.map(v => Math.round(Math.max(0, Math.min(1, (v - 155) / 90)) ** 1.5 * 255)));
        await sharp(mask, { raw: info }).webp({ lossless: true }).toFile(fileURLToPath(new URL(`${source}-gloss.webp`, root)));
    }
}

// Crop before tinting, at native resolution. Custom colors use these same rectangles in SVG viewBox.
const imports = [];
const entries = [];
for (const [name, crop] of Object.entries(materialCrops)) {
    const { source, role, finish, left, top, width, height } = crop;
    const { data, info } = await sharp(fileURLToPath(new URL(`${source}-neutral.webp`, root)))
        .extract({ left, top, width, height }).greyscale().raw().toBuffer({ resolveWithObject: true });
    const modes = role === "cut" ? ["light"] : ["light", "dark"];
    const variants = {};
    for (const mode of modes) {
        const ramp = materialRamp(DEFAULT_MATERIAL_COLOR, mode, role, finish);
        const rgb = Buffer.alloc(info.width * info.height * 3);
        for (let i = 0; i < data.length; i++) {
            const position = data[i] / 255 * (ramp.length - 1);
            const a = Math.min(ramp.length - 2, Math.floor(position));
            const t = position - a;
            for (let channel = 0; channel < 3; channel++) rgb[i * 3 + channel] = Math.round(ramp[a][channel] + (ramp[a + 1][channel] - ramp[a][channel]) * t);
        }
        const file = `crop-${name}-${mode}.webp`;
        await sharp(rgb, { raw: { width, height, channels: 3 } }).webp({ quality: 96, effort: 5 }).toFile(fileURLToPath(new URL(`generated/${file}`, root)));
        const binding = `${name}_${mode}`;
        imports.push(`import ${binding} from "./generated/${file}";`);
        variants[mode] = binding;
    }
    entries.push(`    ${name}: { light: ${variants.light}, dark: ${variants.dark ?? variants.light} },`);
    console.log(`crop-${name}`);
}
await writeFile(new URL("cropTextures.ts", root), `// Generated by scripts/prepare-gem-materials.mjs; crop definitions live in materialCrops.ts.\n${imports.join("\n")}\n\nexport const cropTextures = {\n${entries.join("\n")}\n};\n`);
